/**
 * Gets the active language from state or localStorage
 */
export function getAppLanguage() {
    return (window.state && window.state.lang) || localStorage.getItem('app_lang') || 'en';
}

/**
 * Translates a key according to the active application language
 * @param {string} key - The dictionary key
 * @param {string} fallbackEn - Fallback English text if key is not found
 */
export function t(key, fallbackEn = '') {
    const lang = getAppLanguage();
    if (translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    if (translations['en'] && translations['en'][key]) {
        return translations['en'][key];
    }
    return fallbackEn || key;
}

/**
 * Scans all elements with data-i18n attribute and updates their text content
 */
export function updateStaticDomTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            el.textContent = t(key, el.textContent);
        }
    });
}

/**
 * Sets the active language globally and updates local storage
 */
export function setAppLanguage(lang) {
    const targetLang = (lang === 'sw' || lang === 'SW') ? 'sw' : 'en';
    localStorage.setItem('app_lang', targetLang);
    localStorage.setItem('ai_lang', targetLang);

    if (window.state) {
        window.state.lang = targetLang;
    }

    // Persist language preference to Supabase Profiles DB
    const userId = window.state?.profile?.id || window.state?.ownerId;
    if (userId && window.supabaseClient) {
        window.supabaseClient
            .from('profiles')
            .update({ preferred_language: targetLang, language: targetLang, updated_at: new Date().toISOString() })
            .eq('id', userId)
            .then(({ error }) => {
                if (error) console.warn('[i18n] Failed saving language preference to Supabase:', error.message);
            })
            .catch(() => {});
    }

    // Update Language Toggle Badge in Top Nav & More Menu
    const label = document.getElementById('langToggleLabel');
    if (label) label.textContent = targetLang.toUpperCase();
    const moreMenuLabel = document.getElementById('moreMenuLangLabel');
    if (moreMenuLabel) moreMenuLabel.textContent = targetLang.toUpperCase();

    // Update Static DOM Elements
    updateStaticDomTranslations();

    // Sync AI assistant language badge if present
    if (window.selectAiLanguage) {
        window.selectAiLanguage(targetLang);
    }

    // Re-render UI
    if (window.refreshCurrentViewLanguage) {
        window.refreshCurrentViewLanguage();
    }
}

// Expose globally to window
window.t = t;
window.getAppLanguage = getAppLanguage;
window.setAppLanguage = setAppLanguage;
window.updateStaticDomTranslations = updateStaticDomTranslations;
window.toggleAppLanguage = function() {
    const current = getAppLanguage();
    const nextLang = current === 'en' ? 'sw' : 'en';
    setAppLanguage(nextLang);
};

/**
 * Restores language from a user profile object.
 * Called after session restore on page refresh.
 */
export function restoreLanguageFromProfile(profile) {
    if (!profile) return;
    const dbLang = profile.preferred_language || profile.language;
    if (dbLang && (dbLang === 'sw' || dbLang === 'en')) {
        // Only set if it differs from what's already active, to avoid unnecessary re-renders
        const currentLang = getAppLanguage();
        if (dbLang !== currentLang) {
            setAppLanguage(dbLang);
        } else {
            // Still sync the badge and DOM even if same language
            const label = document.getElementById('langToggleLabel');
            if (label) label.textContent = dbLang.toUpperCase();
            const moreMenuLabel = document.getElementById('moreMenuLangLabel');
            if (moreMenuLabel) moreMenuLabel.textContent = dbLang.toUpperCase();
            updateStaticDomTranslations();
        }
    }
}
window.restoreLanguageFromProfile = restoreLanguageFromProfile;

/**
 * BOOT-TIME INIT: Immediately sync lang badge and state from localStorage.
 * This runs once when the module loads, fixing the refresh issue.
 */
(function bootLanguageSync() {
    const savedLang = localStorage.getItem('app_lang') || 'en';
    // Sync state.lang if state is already available
    if (window.state) {
        window.state.lang = savedLang;
    }
    // Update the language toggle badge immediately
    const syncBadge = () => {
        const label = document.getElementById('langToggleLabel');
        if (label) {
            label.textContent = savedLang.toUpperCase();
        }
        const moreMenuLabel = document.getElementById('moreMenuLangLabel');
        if (moreMenuLabel) {
            moreMenuLabel.textContent = savedLang.toUpperCase();
        }
    };
    // Try immediately, and also after DOM is ready
    syncBadge();
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', syncBadge);
    }
})();
